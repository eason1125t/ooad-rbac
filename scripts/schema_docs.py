"""从唯一Flyway DDL生成中文字段字典与可编辑ER，供07数据库设计说明引用。

不连接数据库；真实迁移执行由backend集成测试验证。解析仅支持项目当前的显式DDL格式。
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def definitions(body: str) -> list[str]:
    """只在括号/SQL引号外拆逗号，保留复合键、生成表达式和注释。"""
    result, start, depth, quoted = [], 0, 0, False
    index = 0
    while index < len(body):
        char = body[index]
        if char == "'":
            if quoted and index + 1 < len(body) and body[index + 1] == "'":
                index += 2
                continue
            quoted = not quoted
        elif not quoted:
            depth += (char == "(") - (char == ")")
            if char == "," and depth == 0:
                result.append(" ".join(body[start:index].split()))
                start = index + 1
        index += 1
    if quoted or depth != 0:
        raise ValueError("Unbalanced DDL definition")
    result.append(" ".join(body[start:].split()))
    return [item for item in result if item]


def current_tables() -> dict[str, list[str]]:
    """按版本重放当前显式CREATE和ADD；遇到未知结构变更拒绝生成过期文档。"""
    result: dict[str, list[str]] = {}
    migrations = ROOT / "backend/src/main/resources/db/migration"
    files = sorted(migrations.glob("V*__*.sql"), key=lambda p: tuple(int(n) for n in p.name[1:].split("__")[0].split("_")))
    for path in files:
        sql = path.read_text(encoding="utf-8")
        events = [(m.start(), "create", m) for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\) ENGINE", sql, re.S)]
        events += [(m.start(), "alter", m) for m in re.finditer(r"ALTER TABLE (\w+)\s+(.*?);", sql, re.S)]
        for _, kind, match in sorted(events, key=lambda item: item[0]):
            table, body = match.group(1, 2)
            if kind == "create":
                if table in result:
                    raise ValueError(f"Duplicate table {table}")
                result[table] = definitions(body)
            else:
                for item in definitions(body):
                    if not re.match(r"ADD (COLUMN |CONSTRAINT |INDEX )", item):
                        raise ValueError(f"Unsupported ALTER in {path.name}: {table}")
                    result[table].append(re.sub(r"^ADD (COLUMN )?", "", item))
    return result


def generate() -> None:
    """保留全部迁移后的列及约束，不把DDL以外的设计稿混入当前数据库。"""
    tables = current_tables()
    dictionary = ["// 自动生成：scripts/schema_docs.py；字段与约束来自Flyway，禁止手工改生成结果。", "= 数据库表与字段字典", ":toc: left", ":toclevels: 1", "", f"当前{len(tables)}张业务表，不含Flyway历史表。设计与表职责见link:07-数据库设计说明.adoc[07]。默认/生成值、注释及约束从迁移解析；可执行DDL仍以迁移为准。", ""]
    er = ["%% Generated by scripts/schema_docs.py from Flyway.", "erDiagram"]
    for name, entries in tables.items():
        body = "\n".join(entries)
        dictionary.extend([f"== {name}", "", "[cols=\"2,2,1,4,5\",options=\"header\"]", "|===", "|字段 |类型 |可空 |默认/生成 |说明"])
        er.append(f"  {name} {{")
        constraints = []
        for raw in entries:
            line = raw.strip().removesuffix(",")
            if not line:
                continue
            column = re.match(r"(\w+) (BIGINT|INT|CHAR\(\d+\)|VARCHAR\(\d+\)|BOOLEAN|DATETIME\(3\)|JSON)(.*)", line)
            if column:
                field, kind = column.group(1, 2)
                rest = column.group(3)
                comment = re.search(r"COMMENT '((?:''|[^'])*)'", rest)
                description = comment.group(1).replace("''", "'") if comment else "—"
                default = re.search(r"DEFAULT (NULL|TRUE|FALSE|CURRENT_TIMESTAMP(?:\(\d+\))?|'(?:''|[^'])*'|-?\d+)", rest)
                generated = re.search(r"GENERATED ALWAYS AS \((.*)\) STORED", rest)
                value = f"生成：{generated.group(1)}" if generated else default.group(1) if default else "—"
                if "AUTO_INCREMENT" in rest:
                    value = "自增"
                cell = lambda text: str(text).replace("|", "\\|")
                dictionary.append(f"|`{field}` |`{kind}` |{'否' if 'NOT NULL' in rest else '是'} |{cell(value)} |{cell(description)}")
                er.append(f"    {kind.split('(')[0]} {field}")
            else:
                constraints.append(line)
        dictionary.extend(["|===", ""])
        dictionary.extend(["约束与索引（保留实际SQL定义）：", "", "[source,sql]", "----", *constraints, "----", ""])
        er.append("  }")
        for fields, parent, referenced in re.findall(r"FOREIGN KEY\s*\(([^)]+)\) REFERENCES (\w+)\(([^)]+)\)", body):
            names = [field.strip() for field in fields.split(",")]
            optional = all(re.search(rf"^\s*{field} BIGINT NULL", body, re.M) is not None for field in names)
            unique = re.search(rf"UNIQUE\s*\({re.escape(fields)}\)", body) is not None
            left = "|o" if optional else "||"
            right = "o|" if unique else "o{"
            er.append(f'  {parent} {left}--{right} {name} : "{fields.replace(",", "_")}"')
    (ROOT / "docs/diagrams").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs/08-数据库表与字段字典.adoc").write_text("\n".join(dictionary), encoding="utf-8", newline="\n")
    (ROOT / "docs/diagrams/er.mmd").write_text("\n".join(er) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()
