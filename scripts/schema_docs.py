"""从唯一Flyway DDL生成字段字典与可编辑Mermaid ER，供docs/design.adoc引用。

不连接数据库；真实迁移执行由backend集成测试验证。解析仅支持项目当前的显式DDL格式。
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate() -> None:
    """保留完整列定义和约束，避免独立手写字典与迁移漂移。"""
    sql = (ROOT / "backend/src/main/resources/db/migration/V1__identity_and_rbac0.sql").read_text(encoding="utf-8")
    tables = re.findall(r"CREATE TABLE (\w+) \((.*?)\) ENGINE", sql, re.S)
    if len(tables) != 8:
        raise ValueError("Expected eight current schema tables")
    dictionary = ["// Generated by scripts/schema_docs.py from Flyway; do not edit.", "= 数据字典（生成）", ""]
    er = ["%% Generated by scripts/schema_docs.py from Flyway.", "erDiagram"]
    for name, body in tables:
        dictionary.extend([f"== {name}", "", "[cols=\"1,5\",options=\"header\"]", "|===", "|字段/约束 |定义"])
        er.append(f"  {name} {{")
        for raw in body.splitlines():
            line = raw.strip().removesuffix(",")
            if not line:
                continue
            column = re.match(r"(\w+) (BIGINT|VARCHAR\(\d+\)|BOOLEAN|DATETIME\(3\))(.*)", line)
            # 每个字段原样输出NULL、默认值和注释；键/索引也保持在字典中。
            dictionary.append(f"|`{line.split()[0]}` |`{line}`")
            if column:
                field, kind = column.group(1, 2)
                er.append(f"    {kind.split('(')[0]} {field}")
        dictionary.extend(["|===", ""])
        er.append("  }")
        for field, parent in re.findall(r"FOREIGN KEY \((\w+)\) REFERENCES (\w+)\(id\)", body):
            optional = re.search(rf"^\s*{field} BIGINT NULL", body, re.M) is not None
            unique = re.search(rf"UNIQUE \({field}\)", body) is not None
            left = "|o" if optional else "||"
            right = "o|" if unique else "o{"
            er.append(f'  {parent} {left}--{right} {name} : "{field}"')
    (ROOT / "docs/diagrams").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs/database.generated.adoc").write_text("\n".join(dictionary), encoding="utf-8")
    (ROOT / "docs/diagrams/er.mmd").write_text("\n".join(er) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
